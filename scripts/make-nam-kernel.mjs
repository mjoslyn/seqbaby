// Assemble scripts/nam-kernel.wat into public/js/namKernel.js (the bytes as
// base64), which nam.js puts in its worklet. Run after editing the .wat:
//
//   npm i --no-save wabt@1.0.36 && node scripts/make-nam-kernel.mjs
//
// The output is committed, so nothing else needs wabt.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const wabt = await (await import(process.env.WABT_PATH || "wabt")).default();
const src = fs.readFileSync(path.join(here, "nam-kernel.wat"), "utf8");
const mod = wabt.parseWat("nam-kernel.wat", src, { simd: true });
mod.validate();
const { buffer } = mod.toBinary({});
const b64 = Buffer.from(buffer).toString("base64");
const out = `// Generated by scripts/make-nam-kernel.mjs from scripts/nam-kernel.wat. Do not edit.
// The NAM stage's WebAssembly SIMD inner loops (${buffer.length} bytes).
export const NAM_KERNEL_B64 = "${b64}";
`;
fs.writeFileSync(path.join(here, "..", "public", "js", "namKernel.js"), out);
console.log(`namKernel.js: ${buffer.length} bytes`);
